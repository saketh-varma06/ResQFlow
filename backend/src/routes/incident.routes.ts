import { Router } from "express";
import { requireAuth, requireRole } from "../middleware/auth";
import { validate } from "../middleware/validate";
import { idParam } from "../validators/common";
import { addNoteSchema, assignIncidentSchema, checklistPatchSchema, createIncidentSchema, fieldReportSchema, listIncidentsQuery, markDuplicateSchema, updateIncidentSchema, updateIncidentStatusSchema } from "../validators/incident.validators";
import * as c from "../controllers/incident.controller";
export const incidentRouter = Router();
incidentRouter.use(requireAuth);
incidentRouter.post("/", validate({ body: createIncidentSchema }), c.create);
incidentRouter.get("/", validate({ query: listIncidentsQuery }), c.list);
incidentRouter.get("/:id", validate({ params: idParam }), c.getOne);
incidentRouter.patch("/:id", validate({ params: idParam, body: updateIncidentSchema }), c.update);
incidentRouter.patch("/:id/status", validate({ params: idParam, body: updateIncidentStatusSchema }), c.updateStatus);
incidentRouter.post("/:id/assign", requireRole("ADMIN"), validate({ params: idParam, body: assignIncidentSchema }), c.assign);
incidentRouter.post("/:id/accept", requireRole("RESPONDER"), validate({ params: idParam }), c.accept);
incidentRouter.post("/:id/decline", requireRole("RESPONDER"), validate({ params: idParam }), c.decline);
incidentRouter.post("/:id/complete", requireRole("RESPONDER"), validate({ params: idParam }), c.complete);
incidentRouter.post("/:id/notes", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam, body: addNoteSchema }), c.addNote);
incidentRouter.delete("/:id", requireRole("ADMIN"), validate({ params: idParam }), c.remove);
incidentRouter.get("/:id/duplicates", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.duplicates);
incidentRouter.post("/:id/verify", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.verify);
incidentRouter.post("/:id/mark-duplicate", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam, body: markDuplicateSchema }), c.markDuplicate);
incidentRouter.post("/:id/unflag-duplicate", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.unflagDuplicate);
incidentRouter.post("/:id/claim", requireRole("RESPONDER"), validate({ params: idParam }), c.claim);
incidentRouter.post("/:id/release", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.release);
incidentRouter.get("/:id/dispatch", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.dispatch);
incidentRouter.get("/:id/route", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam }), c.route);
incidentRouter.get("/:id/checklist", validate({ params: idParam }), c.getChecklist);
incidentRouter.patch("/:id/checklist", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam, body: checklistPatchSchema }), c.patchChecklist);
incidentRouter.get("/:id/field-reports", validate({ params: idParam }), c.listFieldReports);
incidentRouter.post("/:id/field-reports", requireRole("RESPONDER", "ADMIN"), validate({ params: idParam, body: fieldReportSchema }), c.createFieldReport);
